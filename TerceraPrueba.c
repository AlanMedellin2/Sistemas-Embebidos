void Green_Task(void *argument){
	for(;;){
		HAL_GPIO_TogglePin(LED_VERDE_GPIO_Port, LED_VERDE_Pin);
		osDelay(250);
	}
}

void Yellow_Task(void *argument){
	for(;;){
		if(osSemaphoreAcquire(buttonSemHandle, osWaitForever) == osOK){
			HAL_GPIO_WritePin(LED_AMARILLO_GPIO_Port, LED_AMARILLO_Pin, 1);
			osDelay(500);
			HAL_GPIO_WritePin(LED_AMARILLO_GPIO_Port, LED_AMARILLO_Pin, 0);
			osDelay(500);
			HAL_ADC_Start(&hadc2);
			HAL_ADC_PollForConversion(&hadc2, 1000);
			buffer = HAL_ADC_GetValue(&hadc2);
			adc_value16 = (uint16_t)buffer;
			osMessageQueuePut(queueSpeedHandler, &adc_value16, 0, 0);
			sprintf(msg, "ADC: %lu\r\n", buffer);
			if (osMutexAcquire(uartMutexHandle, 500) == osOK) {
				/* Timeout 500ms: si falla el acquire, se omite la transmisión para no quedar bloqueado por mucho tiempo */
				HAL_UART_Transmit(&huart3, (uint8_t*)msg, strlen(msg), 1000);
				osMutexRelease(uartMutexHandle);
			}

		}

	}

}

void Red_Task(void *argument){
	uint32_t items = 0;
	uint16_t newValue = 0;
	float32_t promedio = 0;
	float32_t array[5]={0};
	for(;;){

		HAL_GPIO_WritePin(LED_ROJO_GPIO_Port, LED_ROJO_Pin, 1);
		osDelay(30000);
		HAL_GPIO_WritePin(LED_ROJO_GPIO_Port, LED_ROJO_Pin, 0);

		promedio = 0;
		items = osMessageQueueGetCount(queueSpeedHandler);

		if(items>0){
			for(int i=0;i<items;i++){
				if (osMessageQueueGet(queueSpeedHandler, &newValue, NULL, 0) == osOK){
					array[i]=(float32_t)newValue;
				}
			}
			arm_mean_f32(array, items, &promedio);
		}


		if (osMutexAcquire(uartMutexHandle, 500) == osOK){
			if (items == 0)
			{
				sprintf((char*)msg, "No hay valores disponibles.\r\n");
			}
			else
			{
				//Sacar promedio de sum
				sprintf((char*)msg, "Promedio: %.2f (usando %lu valores)\r\n", promedio, items);
			}

			HAL_UART_Transmit(&huart3, msg, strlen((char*)msg), 1000);
			osMutexRelease(uartMutexHandle);
		}
	}
}

