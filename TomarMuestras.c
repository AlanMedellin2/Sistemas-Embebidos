/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */
/* USER CODE BEGIN Boot_Mode_Sequence_0 */
#if defined(DUAL_CORE_BOOT_SYNC_SEQUENCE)
  int32_t timeout;
#endif /* DUAL_CORE_BOOT_SYNC_SEQUENCE */
/* USER CODE END Boot_Mode_Sequence_0 */

/* USER CODE BEGIN Boot_Mode_Sequence_1 */
#if defined(DUAL_CORE_BOOT_SYNC_SEQUENCE)
  /* Wait until CPU2 boots and enters in stop mode or timeout*/
  timeout = 0xFFFF;
  while((__HAL_RCC_GET_FLAG(RCC_FLAG_D2CKRDY) != RESET) && (timeout-- > 0));
  if ( timeout < 0 )
  {
  Error_Handler();
  }
#endif /* DUAL_CORE_BOOT_SYNC_SEQUENCE */
/* USER CODE END Boot_Mode_Sequence_1 */
  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();
/* USER CODE BEGIN Boot_Mode_Sequence_2 */
#if defined(DUAL_CORE_BOOT_SYNC_SEQUENCE)
/* When system initialization is finished, Cortex-M7 will release Cortex-M4 by means of
HSEM notification */
/*HW semaphore Clock enable*/
__HAL_RCC_HSEM_CLK_ENABLE();
/*Take HSEM */
HAL_HSEM_FastTake(HSEM_ID_0);
/*Release HSEM in order to notify the CPU2(CM4)*/
HAL_HSEM_Release(HSEM_ID_0,0);
/* wait until CPU2 wakes up from stop mode */
timeout = 0xFFFF;
while((__HAL_RCC_GET_FLAG(RCC_FLAG_D2CKRDY) == RESET) && (timeout-- > 0));
if ( timeout < 0 )
{
Error_Handler();
}
#endif /* DUAL_CORE_BOOT_SYNC_SEQUENCE */
/* USER CODE END Boot_Mode_Sequence_2 */

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_TIM6_Init();
  MX_USART3_UART_Init();
  /* USER CODE BEGIN 2 */

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	  switch(devState){
	  	  case IDLE:

	  		  HAL_GPIO_WritePin(LED_ROJO_GPIO_Port, LED_ROJO_Pin, 0);
	  		  HAL_GPIO_WritePin(LED_AMARILLO_GPIO_Port, LED_AMARILLO_Pin, 0);
	  		  HAL_GPIO_WritePin(LED_VERDE_GPIO_Port, LED_VERDE_Pin, 1);

	  		  cont=0;
	  		  start=0;


				break;

	  	  case MEASURE:

	  		  HAL_GPIO_WritePin(LED_ROJO_GPIO_Port, LED_ROJO_Pin, 1);
			  HAL_GPIO_WritePin(LED_AMARILLO_GPIO_Port, LED_AMARILLO_Pin, 0);
			  HAL_GPIO_WritePin(LED_VERDE_GPIO_Port, LED_VERDE_Pin, 0);

			  iniciar();


			  if(cont<10 && start==1){

				 HAL_GPIO_WritePin(LED_VERDE_GPIO_Port, LED_VERDE_Pin, 1);
				 adcReady=false;
				 HAL_TIM_Base_Start(&htim6);
				 HAL_ADC_Start_DMA(&hadc1, (uint32_t*)mic, 32000);
				 start=0;

			  }

			  if(adcReady && cont<10){

				 HAL_GPIO_WritePin(LED_VERDE_GPIO_Port, LED_VERDE_Pin, 0);
				 procesar(mic,32000, &zcrPersona,&centroidPersona, &bwPersona, &rolloffPersona);

				 zcrPerfil[cont]=zcrPersona;
				 centroidPerfil[cont]=centroidPersona;
				 bwPerfil[cont]=bwPersona;
				 rolloffPerfil[cont]=rolloffPersona;

				 cont++;
				 adcReady=false;
			  }

			  if(cont >=10){
				  devState=MEAN;
			  }


			  break;

	  	  case MEAN:


	  		 arm_mean_f32(zcrPerfil, MUESTRAS, &zcrFinal);
	  		 arm_mean_f32(centroidPerfil,MUESTRAS,&centroidFinal);
	  		 arm_mean_f32(bwPerfil,MUESTRAS,&bwFinal);
	  		 arm_mean_f32(rolloffPerfil,MUESTRAS,&rolloffFinal);

	  		 perfilPersona[0]=zcrFinal;
	  		 perfilPersona[1]=centroidFinal;
	  		 perfilPersona[2]=bwFinal;
	  		 perfilPersona[3]=rolloffFinal;


	  		 devState=UART;


	  		  break;

	  	  case UART:

	  		  HAL_GPIO_WritePin(LED_ROJO_GPIO_Port, LED_ROJO_Pin, 0);
			  HAL_GPIO_WritePin(LED_AMARILLO_GPIO_Port, LED_AMARILLO_Pin, 1);
			  HAL_GPIO_WritePin(LED_VERDE_GPIO_Port, LED_VERDE_Pin, 0);


			  if (adcReady)
			  {
			      adcReady = 0;

			      // Enviar cada muestra como texto
			      char buffer[20];
			      for (int i = 0; i < 4; i++) {
			          int len = sprintf(buffer, "%0.4f\r\n", perfilPersona[i]);
			          HAL_UART_Transmit(&huart3, (uint8_t*)buffer, len, HAL_MAX_DELAY);
			      }

			      devState = IDLE;
			  }

	  		   break;


	  	  default:
	  		  break;

	  }

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

